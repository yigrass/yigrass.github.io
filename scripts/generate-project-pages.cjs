// Static deep links reuse the desktop shell. Run after editing index.html or any route configuration.
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const root = path.resolve(__dirname, "..");
const context = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, "assets/site-config.js"), "utf8"), context);
vm.runInNewContext(fs.readFileSync(path.join(root, "assets/project-routes.js"), "utf8"), context);
const shell = fs.readFileSync(path.join(root, "index.html"), "utf8").replace(/\r\n/g, "\n");
const check = process.argv.includes("--check");
const { byPath } = context.window.createDesktopRouteCatalog(context.window.SITE_CONFIG);
for (const route of byPath.keys()) {
  const relativeRoot = "../".repeat(route.split("/").filter(Boolean).length);
  const page = shell.replace("<head>", `<head>\n  <!-- Generated by scripts/generate-project-pages.cjs. Do not edit directly. -->\n  <base href="${relativeRoot}">`);
  const file = path.join(root, route, "index.html");
  if (check) {
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n") !== page) throw new Error(`Outdated desktop entry: ${route}`);
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, page, "utf8");
  }
}
console.log(`${check ? "Checked" : "Generated"} ${byPath.size} desktop entry pages.`);
