// Static deep links reuse the desktop shell. Run after editing index.html or project routes.
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const root = path.resolve(__dirname, "..");
const context = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, "assets/site-config.js"), "utf8"), context);
const shell = fs.readFileSync(path.join(root, "index.html"), "utf8").replace(/\r\n/g, "\n");
const check = process.argv.includes("--check");
const routes = new Set();
for (const project of context.window.SITE_CONFIG.works) {
  if (!project.route) continue;
  if (!/^(?:[a-z0-9-]+\/)+$/.test(project.route) || routes.has(project.route)) throw new Error("Invalid or duplicate project route");
  routes.add(project.route);
  const relativeRoot = "../".repeat(project.route.split("/").filter(Boolean).length);
  const page = shell.replace("<head>", `<head>\n  <!-- Generated by scripts/generate-project-pages.cjs. Do not edit directly. -->\n  <base href="${relativeRoot}">`);
  const file = path.join(root, project.route, "index.html");
  if (check) {
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n") !== page) throw new Error(`Outdated project entry: ${project.route}`);
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, page, "utf8");
  }
}
console.log(`${check ? "Checked" : "Generated"} ${routes.size} project entry pages.`);
