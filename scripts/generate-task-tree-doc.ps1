param([switch]$Check)
$ErrorActionPreference = 'Stop'
$projectRoot = [System.IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$tree = Get-Content -LiteralPath (Join-Path $projectRoot 'project-task-tree.json') -Raw | ConvertFrom-Json
$byId = @{}
foreach ($task in $tree.tasks) {
    if ($byId.ContainsKey($task.id)) { throw "Duplicate task ID: $($task.id)" }
    $byId[$task.id] = $task
}
foreach ($id in @($tree.rootTaskId, $tree.currentContextTaskId, $tree.currentWorkingBranchTaskId) + @($tree.activeExecutionBranches)) {
    if ($null -ne $id -and -not $byId.ContainsKey($id)) { throw "Unknown task reference: $id" }
}
$roots = @($tree.tasks | Where-Object { $null -eq $_.parent })
if ($roots.Count -ne 1 -or $roots[0].id -ne $tree.rootTaskId) { throw 'Expected one declared root.' }
function Get-TaskPath($id) {
    $names = [System.Collections.Generic.List[string]]::new()
    $seen = @{}
    while ($null -ne $id) {
        if (-not $byId.ContainsKey($id)) { throw "Unknown parent: $id" }
        if ($seen.ContainsKey($id)) { throw "Task cycle: $id" }
        $seen[$id] = $true
        $names.Insert(0, $byId[$id].name)
        $id = $byId[$id].parent
    }
    return $names -join ' / '
}
foreach ($task in $tree.tasks) { [void](Get-TaskPath $task.id) }
$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('# Task Tree')
$lines.Add('')
$lines.Add('Generated by `scripts/generate-task-tree-doc.ps1`. DO NOT EDIT MANUALLY. 不得手工编辑。')
$lines.Add('')
$lines.Add('## Current Status')
$lines.Add('')
$lines.Add("- Project: $($tree.projectName)")
$lines.Add("- Current task path: $(Get-TaskPath $tree.currentContextTaskId)")
$lines.Add("- Current task: $($byId[$tree.currentContextTaskId].name)")
$lines.Add("- Status: $($tree.status)")
$lines.Add('- Position: main')
$working = if ($null -eq $tree.currentWorkingBranchTaskId) { 'none' } else { $byId[$tree.currentWorkingBranchTaskId].name }
$branches = @($tree.activeExecutionBranches | ForEach-Object { $byId[$_].name }) -join ', '
if (-not $branches) { $branches = 'none' }
$lines.Add("- Active task: $working")
$lines.Add("- Active branches: $branches")
$lines.Add('')
$lines.Add('## Task Tree')
$lines.Add('')
$lines.Add('```text')
$visited = @{}
function Add-Task($task, $prefix, $edge, $childPrefix) {
    if ($visited.ContainsKey($task.id)) { throw "Repeated task: $($task.id)" }
    $visited[$task.id] = $true
    $markers = @($task.status)
    if ($task.id -eq $tree.currentContextTaskId) { $markers += 'current' }
    if ($task.id -eq $tree.currentWorkingBranchTaskId) { $markers += 'working' }
    $lines.Add("$prefix$edge$($task.name) [$($markers -join '; ')]")
    $children = @($tree.tasks | Where-Object parent -eq $task.id)
    for ($i = 0; $i -lt $children.Count; $i++) {
        $last = $i -eq $children.Count - 1
        $nextEdge = if ($last) { '\-- ' } else { '+-- ' }
        $nextPrefix = if ($last) { '    ' } else { '|   ' }
        Add-Task $children[$i] ($prefix + $childPrefix) $nextEdge $nextPrefix
    }
}
Add-Task $byId[$tree.rootTaskId] '' '' ''
if ($visited.Count -ne $byId.Count) { throw 'Unreachable task nodes.' }
$lines.Add('```')
$output = ($lines -join "`n") + "`n"
$target = Join-Path $projectRoot $tree.metadata.generatedViewPath
if ($Check) {
    if (-not (Test-Path -LiteralPath $target -PathType Leaf) -or [System.IO.File]::ReadAllText($target) -cne $output) { throw 'Generated task view is missing or out of date.' }
    Write-Output 'Generated task view is current.'
} else {
    [void][System.IO.Directory]::CreateDirectory([System.IO.Path]::GetDirectoryName($target))
    if (-not (Test-Path -LiteralPath $target) -or [System.IO.File]::ReadAllText($target) -cne $output) {
        [System.IO.File]::WriteAllText($target, $output, [System.Text.UTF8Encoding]::new($false))
    }
    Write-Output 'Generated docs/TASK_TREE.md.'
}
